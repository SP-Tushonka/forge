    <h2 id="introduction">1. Introduction</h2>

    <p>This Privacy Policy explains what personal information The Forge collects, why, who it is shared with, how long
        it is kept, and the rights you have over it.</p>

    <h4 id="quick-summary">Quick Summary:</h4>
    <ul>
        <li>We collect what is needed to run the site, keep it secure and moderate it</li>
        <li>We do not sell your data, show ads, or use analytics or advertising cookies</li>
        <li>Activity records, including IP addresses, are deleted after 12 months</li>
        <li>Bans and their records are kept permanently</li>
        <li>You can ask for a copy of your data, or for it to be corrected or deleted</li>
    </ul>

    <h4 id="who-we-are">Who We Are:</h4>
    <p>The Forge is an open-source community project run by volunteers across the world. It is not a company. The
        project's maintainers decide how your personal data is used, which makes them responsible for it under data
        protection law (the "controller").</p>
    <ul>
        <li><strong>Service:</strong> The Forge (Single Player Tushonka modding platform)</li>
        <li><strong>Website:</strong> https://forge.sp-mod.com</li>
        <li><strong>Contact:</strong> clodan-spt@hotmail.com</li>
    </ul>

    <h2 id="information-we-collect">2. Information We Collect</h2>

    <h3 id="information-you-provide">2.1 Information You Provide Directly</h3>

    <h4 id="account-registration">Your Account:</h4>
    <ul>
        <li>Email address and username</li>
        <li>Password (stored only as a one-way hash)</li>
        <li>Optional profile details: about text, avatar, cover image and timezone</li>
        <li>Two-factor authentication settings, if you turn it on</li>
    </ul>

    <h4 id="content-submissions">What You Post:</h4>
    <ul>
        <li>Mods, addons, their versions, descriptions, images and download links</li>
        <li>Comments, including earlier versions of comments you edit</li>
        <li>Reactions, endorsements, mod lists, follows, and issues you open on mods</li>
        <li>Blocks you place on other members, and the reason you give</li>
        <li>Reports you file about content or members</li>
    </ul>

    <h4 id="communications">Messages:</h4>
    <ul>
        <li>Private messages you send through the site, and when you read them</li>
        <li>Emails you send us</li>
    </ul>

    <h3 id="information-collected-automatically">2.2 Information Collected Automatically</h3>

    <h4 id="website-usage-data">Activity Records:</h4>
    <p>When you use the site we record activity such as page visits and account events (for example signing in or
        publishing a mod). Each record can include:</p>
    <ul>
        <li>The page and the page you came from</li>
        <li>Your IP address</li>
        <li>An approximate location worked out from your IP address: country, region, city and time zone. The lookup
            uses a database on our own server; your IP address is not sent anywhere for this</li>
        <li>Your browser, operating system, device type and preferred languages</li>
    </ul>

    <h4 id="technical-information">With Your Comments:</h4>
    <p>When you post a comment we also store your IP address, browser and the page you came from, to help deal with
        spam and abuse.</p>

    <h4 id="performance-data">API Use:</h4>
    <p>If you or your software use our public API, we count requests per IP address to protect the service.</p>

    <h3 id="third-party-authentication">2.3 Signing In With Discord</h3>

    <p>If you link a Discord account, we receive and store your Discord ID, username, display name, avatar, email
        address (if Discord shares it) and whether you use multi-factor authentication on Discord. We do not keep the
        sign-in tokens Discord issues, so we cannot access your Discord account.</p>

    <h2 id="how-we-use-information">3. How We Use Your Information</h2>

    <ul>
        <li><strong>Running your account:</strong> signing you in, account recovery, and your settings</li>
        <li><strong>Hosting what you publish:</strong> showing your mods, comments and profile to others</li>
        <li><strong>Messaging and notifications:</strong> delivering private messages and site notifications, and
            sending account emails such as password resets</li>
        <li><strong>Security and abuse prevention:</strong> detecting spam, attacks and misuse</li>
        <li><strong>Moderation:</strong> handling reports and enforcing our rules. To stop banned members from
            returning, staff can compare the IP addresses used by different accounts</li>
        <li><strong>Understanding how the site is used:</strong> for example which pages are visited and which
            browsers people use, so we can fix problems and improve the site</li>
        <li><strong>Legal requirements:</strong> responding to lawful requests</li>
    </ul>

    <p>We do not send newsletters or marketing email.</p>

    <h2 id="legal-basis-processing">4. Legal Basis for Processing</h2>

    <p>Under the GDPR we rely on:</p>

    <h4 id="contract-performance-art-6-1-b">Contract (Art. 6(1)(b)):</h4>
    <ul>
        <li>Your account, what you publish, your messages and notifications: this is the service you signed up for
        </li>
    </ul>

    <h4 id="legitimate-interests-art-6-1-f">Legitimate Interests (Art. 6(1)(f)):</h4>
    <ul>
        <li>Keeping the site secure and free of spam and abuse</li>
        <li>Moderation, including comparing IP addresses to detect ban evasion, and keeping ban records permanently
            so bans stay enforceable</li>
        <li>Activity records, to understand and improve how the site is used</li>
        <li>Announcing newly published mods and addons on our Discord server</li>
    </ul>
    <p>You can object to processing based on legitimate interests (see section 8).</p>

    <h4 id="legal-compliance-art-6-1-c">Legal Obligation (Art. 6(1)(c)):</h4>
    <ul>
        <li>Responding to lawful requests from authorities, and meeting our data protection obligations</li>
    </ul>

    <p>We do not currently rely on consent for anything.</p>

    <h2 id="data-sharing-disclosure">5. Data Sharing and Disclosure</h2>

    <h3 id="5-1-public-information">5.1 Public Information</h3>
    <p>The following is visible to anyone by design:</p>
    <ul>
        <li>Your username, avatar, cover image and about text</li>
        <li>Mods and addons you publish, and their details</li>
        <li>Your comments and reactions, and other activity shown on your profile</li>
    </ul>

    <h4 id="private-information">Private Messages:</h4>
    <ul>
        <li>Private messages are visible only to the people in the conversation</li>
        <li>Staff may access them only to enforce our Terms of Service or to comply with the law</li>
    </ul>

    <h3 id="5-2-third-party-services">5.2 Service Providers</h3>
    <p>We use these providers to run the site. They receive only what they need for the job described:</p>
    <ul>
        <li><strong>Our hosting provider:</strong> runs our server in Germany, where the database and our search
            index are stored</li>
        <li><strong>Cloudflare:</strong> every visit passes through Cloudflare, which protects the site and speeds
            it up. It sees your IP address and the pages you request</li>
        <li><strong>Cloudflare R2:</strong> stores uploaded files, avatars and cover images</li>
        <li><strong>Google:</strong> some of our emails are delivered through Google's mail service, depending on
            your email provider</li>
        <li><strong>Discord:</strong> handles sign-in if you link a Discord account. When you publish a mod or addon,
            an announcement including your username is posted to our Discord server</li>
        <li><strong>Anthropic:</strong> comment translation. When it is switched on, comment text is sent to
            Anthropic to be translated. It is currently switched off</li>
        <li><strong>Akismet (Automattic):</strong> spam checking. When it is switched on, a new comment's text and
            your username, email address, IP address and browser are sent to Akismet. It is currently switched off
        </li>
    </ul>
    <p>Our own server sends most of our email; your address is not passed to a mailing service.</p>

    <h3 id="5-3-legal-requirements">5.3 Legal Requirements</h3>
    <p>We may disclose information when the law requires it, for example in response to a court order.</p>

    <h3 id="5-4-content-from-other-websites">5.4 Content From Other Websites</h3>
    <p>Apart from Cloudflare, the site's own files, including fonts and default avatars, come from our own server. Two
        things can still make your browser contact another website:</p>
    <ul>
        <li><strong>Images in posts:</strong> members can include images hosted elsewhere in mod descriptions, comments
            and other posts. When a page shows one, your browser loads it from the website that hosts it, which sees
            your IP address and browser details. We do not control those websites</li>
        <li><strong>YouTube videos:</strong> nothing is loaded from YouTube until you press play. The video then loads
            from YouTube's privacy-enhanced mode, YouTube may store its own cookies or similar data in your browser, and
            Google's privacy policy applies</li>
    </ul>

    <h2 id="data-retention">6. Data Retention</h2>

    <h3 id="6-1-account-data">6.1 Your Account</h3>
    <ul>
        <li><strong>While your account exists:</strong> we keep your account and what you post</li>
        <li><strong>When you delete your account:</strong> it is deleted immediately, along with your comments,
            reactions, endorsements, issues, mod lists, follows, blocks, the reports you filed, your Discord link,
            and your private conversations. Deleting a conversation this way removes it for the other person too.
            Activity records and notifications linked to your account are deleted within a day. Ban records are the
            exception; see 6.4</li>
        <li><strong>Mods and addons you published</strong> stay on the site without an owner after your account is
            deleted. Ask us if you want them removed</li>
    </ul>

    <h3 id="6-2-content-data">6.2 Private Messages</h3>
    <ul>
        <li>Messages are kept while both accounts exist</li>
        <li>"Deleting" a conversation hides it from your inbox; the other person still has it</li>
    </ul>

    <h3 id="6-3-technical-data">6.3 Deleted After 12 Months</h3>
    <ul>
        <li>Activity records, including IP addresses, location, browser and device details</li>
        <li>The IP address, browser and referring page stored with a comment. The comment itself stays</li>
        <li>Notifications</li>
        <li>Account recovery and password reset requests</li>
        <li>Reports that did not lead to moderation action</li>
        <li>Ban-evasion investigations</li>
        <li>Daily API usage counts per IP address. Per-minute counts are deleted after 7 days</li>
    </ul>

    <h3 id="6-4-kept-permanently">6.4 Kept Permanently</h3>
    <ul>
        <li>Bans, including the IP address of an IP ban</li>
        <li>Records of bans being issued and lifted, including the banned account's username and email address at the
            time</li>
        <li>Reports that led to moderation action, and the record of that action</li>
    </ul>
    <p>While an account ban is in force, we also keep the email addresses and IP addresses linked to the banned
        account, even if the account is deleted, so the ban can be enforced. They are deleted within a day of the ban
        being lifted or expiring.</p>

    <h3 id="6-5-logs-and-backups">6.5 Logs and Backups</h3>
    <ul>
        <li><strong>Server logs:</strong> deleted after 14 days</li>
        <li><strong>Backups:</strong> kept for no more than 12 months. If a backup is ever restored, anything past
            the limits above is deleted again the next day</li>
    </ul>

    <h2 id="data-security">7. Data Security</h2>

    <h3 id="7-1-technical-safeguards">7.1 Safeguards</h3>
    <ul>
        <li>All traffic is encrypted in transit (TLS)</li>
        <li>Passwords are stored only as one-way hashes</li>
        <li>Two-factor authentication is available for every account</li>
        <li>Access to the server and database is limited to the project's maintainers</li>
    </ul>

    <h3 id="7-2-breach-notification">7.2 Breach Notification</h3>
    <p>If a breach puts your data at risk, we will report it to the relevant data protection authority within 72 hours
        where the law requires, and tell affected members without undue delay.</p>

    <h2 id="your-privacy-rights">8. Your Privacy Rights</h2>

    <p>You have the right to:</p>
    <ul>
        <li><strong>Access:</strong> get a copy of the personal data we hold about you</li>
        <li><strong>Rectification:</strong> have inaccurate data corrected. You can edit most of your profile
            yourself</li>
        <li><strong>Erasure:</strong> have your data deleted. You can delete your account yourself from your profile
            settings</li>
        <li><strong>Restriction:</strong> ask us to limit how we use your data, for example while a dispute is
            resolved</li>
        <li><strong>Objection:</strong> object to processing based on legitimate interests</li>
        <li><strong>Portability:</strong> receive the data you gave us in a structured, machine-readable format</li>
    </ul>

    <p>To use any of these rights, email clodan-spt@hotmail.com. We may ask you to confirm you own the account. We
        will reply within one month. Some requests have legal limits: for example, we will not delete a ban record,
        or the email and IP addresses kept with a ban that is still in force, because they are needed to keep the ban
        enforceable.</p>

    <h2 id="cookies-tracking">9. Cookies</h2>

    <p>We only use cookies that the site needs to work:</p>
    <ul>
        <li>Your sign-in session, and a "remember me" cookie if you choose to stay signed in</li>
        <li>A security token that protects forms</li>
        <li>Short-lived security cookies set by Cloudflare to tell people apart from bots</li>
    </ul>
    <p>We do not use analytics or advertising cookies, so there is nothing to opt in or out of. The activity records
        described in section 2.2 are kept on our server, not in cookies.</p>

    <h2 id="international-transfers">10. Where Your Data Is Stored</h2>

    <p>Our database, search index and server logs are on a server in Germany, inside the EU.</p>

    <p>Cloudflare, Google, Discord, Anthropic and Automattic are based in the United States, so what they receive
        (see section 5.2) may be processed there. These transfers rely on the safeguards the providers offer, such as
        the EU–US Data Privacy Framework or the European Commission's standard contractual clauses.</p>

    <h2 id="childrens-privacy">11. Children's Privacy</h2>

    <p>The Forge requires users to be at least 18 years old. We do not knowingly collect personal information from
        anyone under 18. If we find an account belongs to someone under 18, we will suspend it and delete its data.
        If you believe a child is using the site, please contact us.</p>

    <h2 id="changes-policy">12. Changes to This Policy</h2>

    <p>When this policy changes we will update the dates at the top of this page, and announce significant changes
        on the site before they take effect.</p>

