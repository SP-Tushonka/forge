    <h3 id="13-1-general-privacy-questions">13.1 Contact</h3>
    <p>For any privacy question or request: <strong>clodan-spt@hotmail.com</strong></p>

    <h3 id="13-2-complaints">13.2 Complaints</h3>
    <p>If you are unhappy with how we handle your data, please contact us first. You also have the right to complain
        to the data protection authority where you live or work. Authorities in the EU/EEA are listed at
        https://www.edpb.europa.eu/about-edpb/about-edpb/members_en.</p>

